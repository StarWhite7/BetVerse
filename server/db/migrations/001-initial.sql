CREATE TABLE IF NOT EXISTS users (
 id TEXT PRIMARY KEY, email TEXT NOT NULL UNIQUE COLLATE NOCASE,
 username TEXT NOT NULL UNIQUE COLLATE NOCASE, passwordHash TEXT NOT NULL,
 role TEXT NOT NULL DEFAULT 'USER' CHECK(role IN ('USER','ADMIN')),
 xp INTEGER NOT NULL DEFAULT 0 CHECK(xp >= 0), createdAt TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
 tokenHash TEXT PRIMARY KEY, userId TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 csrf TEXT NOT NULL, expiresAt INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions(userId);
CREATE TABLE IF NOT EXISTS password_resets (
 tokenHash TEXT PRIMARY KEY, userId TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 expiresAt INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS wallets (
 id TEXT PRIMARY KEY, userId TEXT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
 balance INTEGER NOT NULL DEFAULT 0 CHECK(balance BETWEEN 0 AND 1000000000000),
 shards INTEGER NOT NULL DEFAULT 100 CHECK(shards >= 0), lastClaimAt INTEGER,
 createdAt TEXT NOT NULL, updatedAt TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS ledger (
 id TEXT PRIMARY KEY, userId TEXT NOT NULL REFERENCES users(id), amount INTEGER NOT NULL CHECK(amount > 0),
 type TEXT NOT NULL CHECK(type IN ('CREDIT','DEBIT')), reason TEXT NOT NULL,
 reference TEXT NOT NULL, createdAt TEXT NOT NULL,
 UNIQUE(userId, reason, reference)
);
CREATE INDEX IF NOT EXISTS ledger_user ON ledger(userId, createdAt DESC);
CREATE TABLE IF NOT EXISTS matches (
 id TEXT PRIMARY KEY, homeTeam TEXT NOT NULL, awayTeam TEXT NOT NULL, startDate TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'UPCOMING' CHECK(status IN ('UPCOMING','LIVE','FINISHED')),
 result TEXT CHECK(result IN ('HOME','AWAY','DRAW')), homeScore INTEGER, awayScore INTEGER,
 oddsHome INTEGER NOT NULL CHECK(oddsHome BETWEEN 100 AND 100000),
 oddsAway INTEGER NOT NULL CHECK(oddsAway BETWEEN 100 AND 100000),
 oddsDraw INTEGER CHECK(oddsDraw BETWEEN 100 AND 100000),
 sportTitle TEXT NOT NULL DEFAULT 'Football', sportKey TEXT NOT NULL DEFAULT 'football',
 competition TEXT NOT NULL DEFAULT 'Catalogue BetVerse', createdAt TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS matches_date ON matches(status, startDate);
CREATE TABLE IF NOT EXISTS bets (
 id TEXT PRIMARY KEY, userId TEXT NOT NULL REFERENCES users(id), matchId TEXT NOT NULL REFERENCES matches(id),
 match TEXT NOT NULL, betType TEXT NOT NULL CHECK(betType IN ('HOME','AWAY','DRAW')),
 amount INTEGER NOT NULL CHECK(amount BETWEEN 1 AND 1000000), odds INTEGER NOT NULL,
 status TEXT NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','WON','LOST')),
 payout INTEGER, createdAt TEXT NOT NULL, resolvedAt TEXT,
 requestKey TEXT NOT NULL, requestHash TEXT NOT NULL, UNIQUE(userId, requestKey)
);
CREATE INDEX IF NOT EXISTS bets_user ON bets(userId, createdAt DESC);
CREATE INDEX IF NOT EXISTS bets_match ON bets(matchId, status);
CREATE TABLE IF NOT EXISTS agencies (
 id TEXT PRIMARY KEY, name TEXT NOT NULL UNIQUE COLLATE NOCASE, logoId TEXT NOT NULL,
 primaryColor TEXT NOT NULL, secondaryColor TEXT NOT NULL, bannerStyle TEXT NOT NULL DEFAULT 'grid',
 xp INTEGER NOT NULL DEFAULT 0, trophiesCount INTEGER NOT NULL DEFAULT 0,
 createdAt TEXT NOT NULL, updatedAt TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS memberships (
 userId TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 agencyId TEXT NOT NULL REFERENCES agencies(id) ON DELETE CASCADE,
 role TEXT NOT NULL CHECK(role IN ('DIRECTEUR','ASSOCIE','RESPONSABLE','MEMBRE','STAGIAIRE')),
 joinedAt TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS agency_director ON memberships(agencyId) WHERE role = 'DIRECTEUR';
CREATE TABLE IF NOT EXISTS invitations (
 id TEXT PRIMARY KEY, agencyId TEXT NOT NULL REFERENCES agencies(id) ON DELETE CASCADE,
 userId TEXT NOT NULL REFERENCES users(id), inviterId TEXT NOT NULL REFERENCES users(id),
 status TEXT NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','ACCEPTED','DECLINED')),
 createdAt TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS invitation_pending ON invitations(agencyId, userId) WHERE status = 'PENDING';
CREATE TABLE IF NOT EXISTS notifications (
 id TEXT PRIMARY KEY, userId TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 type TEXT NOT NULL, title TEXT NOT NULL, message TEXT NOT NULL, metadata TEXT,
 agencyId TEXT, inviteId TEXT, readAt TEXT, createdAt TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS notifications_user ON notifications(userId, createdAt DESC);
CREATE TABLE IF NOT EXISTS votes (
 userId TEXT NOT NULL REFERENCES users(id), agencyId TEXT NOT NULL REFERENCES agencies(id) ON DELETE CASCADE,
 matchId TEXT NOT NULL REFERENCES matches(id), homeScore INTEGER NOT NULL, awayScore INTEGER NOT NULL,
 points INTEGER NOT NULL DEFAULT 0, resolvedAt TEXT,
 PRIMARY KEY(userId, matchId)
);
CREATE TABLE IF NOT EXISTS agency_results (
 agencyId TEXT NOT NULL REFERENCES agencies(id) ON DELETE CASCADE,
 matchId TEXT NOT NULL REFERENCES matches(id), points INTEGER NOT NULL, createdAt TEXT NOT NULL,
 PRIMARY KEY(agencyId, matchId)
);
CREATE TABLE IF NOT EXISTS audit_log (
 id TEXT PRIMARY KEY, actorId TEXT REFERENCES users(id), action TEXT NOT NULL,
 targetId TEXT, details TEXT, createdAt TEXT NOT NULL
);
